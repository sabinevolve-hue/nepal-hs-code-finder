#!/usr/bin/env python3
"""Cloudflare Workers hosting files, generated from each site's vercel.json (the single source of truth).

    python3 scripts/cf_config.py            # writes public/_redirects, public/_headers, cf/routes.js
                                            #        world/_redirects, world/_headers, world/_cf/routes.js

Cloudflare serves both sites as Workers static assets (free and unlimited requests). Its _redirects file takes plain
paths, ':name' placeholders and one '*' splat, with at most 2,000 static and 100 dynamic rules; it has no regular
expressions. So:
  * plain redirects            -> _redirects (static)
  * ':path*' / ':slug' rules   -> _redirects (dynamic, '*' and ':splat')
  * rules with a regex         -> routes.js, which the Worker script applies to requests that matched no file
                                  (the script never runs for pages that exist, so it costs nothing on normal traffic)
  * vercel.json 'rewrites'     -> _redirects '200' rewrites
  * vercel.json 'headers'      -> _headers; a regex source is expanded to the files it matches in the folder.
Run after world_prerender.py (which writes world/vercel.json) and whenever vercel.json changes; check_pages.py and
the CI build run it too. See DOCUMENTATION.md "Cloudflare hosting".
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITES = [  # (vercel.json, published folder, routes module)
    (ROOT / 'vercel.json', ROOT / 'public', ROOT / 'cf' / 'routes.js'),
    (ROOT / 'world' / 'vercel.json', ROOT / 'world', ROOT / 'world' / '_cf' / 'routes.js'),
]
REGEX_CH = re.compile(r'[()\[\]\\|?+{}]')
HEAD = '# GENERATED by scripts/cf_config.py from vercel.json: edit vercel.json (or its generator), then re-run.\n'


def code(r):
    if 'statusCode' in r:
        return r['statusCode']
    return 308 if r.get('permanent', True) else 307


def vercel_to_regex(src):
    """Vercel path-to-regexp source -> Python/JS regex with named groups."""
    out, i = '', 0
    for m in re.finditer(r':([A-Za-z_]\w*)(\((?:[^()]|\([^()]*\))*\))?(\*)?', src):
        out += re.escape(src[i:m.start()]).replace('\\/', '/')
        name, pat, star = m.group(1), m.group(2), m.group(3)
        if star:
            out += f'(?P<{name}>.*)'
        elif pat:
            out += f'(?P<{name}>{pat[1:-1]})'
        else:
            out += f'(?P<{name}>[^/]+)'
        i = m.end()
    out += re.escape(src[i:]).replace('\\/', '/')
    return '^' + out + '$'


def redirects(cfg, folder):
    static, dynamic, regex = [], [], []
    for r in cfg.get('redirects', []):
        s, d, c = r['source'], r['destination'], code(r)
        if ':' not in s and '*' not in s and not REGEX_CH.search(s):
            static.append(f'{s} {d} {c}')
        elif REGEX_CH.search(s.replace(':path*', '')) or s.count(':') > 1 and '*' in s:
            regex.append((vercel_to_regex(s), d, c))
        elif s.endswith('/:path*') and s.count(':') == 1:
            dynamic.append(f'{s[:-len(":path*")]}* {d.replace(":path*", ":splat")} {c}')
        else:
            dynamic.append(f'{s} {d} {c}')
    rewrites = []
    for r in cfg.get('rewrites', []):
        m = re.fullmatch(r'/\(([\w|-]+)\)', r['source'])
        if m:
            # Vercel applies rewrites only when no file matches; Cloudflare applies _redirects first, so skip routes
            # that have their own page
            rewrites += [f'/{p} {r["destination"]} 200' for p in m.group(1).split('|')
                         if not (folder / f'{p}.html').exists() and not (folder / p / 'index.html').exists()]
        else:
            raise SystemExit(f'cf_config: cannot convert rewrite {r["source"]}')
    if len(static) + len(rewrites) > 2000 or len(dynamic) > 100:
        raise SystemExit(f'cf_config: too many redirects for _redirects ({len(static)} static, {len(dynamic)} dynamic)')
    return static, dynamic, rewrites, regex


def headers(cfg, folder):
    out = []
    for h in cfg.get('headers', []):
        src = h['source']
        if src == '/(.*)':
            paths = ['/*']
        elif re.fullmatch(r'/[\w.-]+/\(\.\*\)', src):
            paths = [src[:-4] + '*']
        elif not REGEX_CH.search(src) and ':' not in src:
            paths = [src] + (['/'] if src == '/index.html' else [])
        else:  # a regex over file names: list the files it matches
            rx = re.compile('^' + src + '$')
            paths = sorted('/' + p.relative_to(folder).as_posix() for p in folder.rglob('*')
                           if p.is_file() and rx.match('/' + p.relative_to(folder).as_posix()))
            if not paths:
                continue
        block = []
        for x in h['headers']:
            block.append(f'  {x["key"]}: {x["value"]}')
        for p in paths:
            out.append((p, block))
    # a later, more specific block that sets Cache-Control must replace (not add to) a /* one; detach it explicitly
    lines = [HEAD]
    for p, block in out:
        lines.append(p)
        if p != '/*' and any(b.strip().lower().startswith('cache-control:') for b in block):
            lines.append('  ! Cache-Control')
        lines += block
        lines.append('')
    # HSTS: Vercel adds it by itself on every response; Cloudflare does not
    if not any(p == '/*' for p, _ in out):
        lines += ['/*', '  Strict-Transport-Security: max-age=63072000', '']
    else:
        i = lines.index('/*')
        lines.insert(i + 1, '  Strict-Transport-Security: max-age=63072000')
    return '\n'.join(lines)


def routes_js(regex):
    rows = ',\n'.join(f'  [{json.dumps(rx.replace("?P<", "?<"))}, {json.dumps(d)}, {c}]' for rx, d, c in regex)
    return ('// GENERATED by scripts/cf_config.py from vercel.json: redirects that need a regular expression.\n'
            '// [pattern, destination with :name placeholders, status]. Applied by the Worker to requests no file matched.\n'
            f'export default [\n{rows}\n];\n')


def main():
    for vj, folder, routes in SITES:
        cfg = json.loads(vj.read_text(encoding='utf-8'))
        static, dynamic, rewrites, regex = redirects(cfg, folder)
        (folder / '_redirects').write_text(HEAD + '\n'.join(static + rewrites + dynamic) + '\n', encoding='utf-8')
        (folder / '_headers').write_text(headers(cfg, folder), encoding='utf-8')
        routes.parent.mkdir(parents=True, exist_ok=True)
        routes.write_text(routes_js(regex), encoding='utf-8')
        print(f'cf_config: {folder.name}: {len(static)} static + {len(dynamic)} dynamic redirects, '
              f'{len(rewrites)} rewrites, {len(regex)} regex redirects (Worker)')


if __name__ == '__main__':
    main()
